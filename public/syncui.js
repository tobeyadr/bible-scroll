// The "Sync across devices" sheet.
import { $, make } from './dom.js'

const ago = time => {
  if (!time) return 'not yet'
  const s = Math.round((Date.now() - time) / 1000)
  if (s < 45) return 'just now'
  if (s < 3600) return `${Math.max(1, Math.round(s / 60))} min ago`
  if (s < 86400) return `${Math.round(s / 3600)} h ago`
  return new Date(time).toLocaleDateString()
}

export function statusLabel(status) {
  if (status.state === 'off') return 'Off'
  if (status.state === 'syncing') return 'Syncing…'
  if (status.state === 'error') return 'Problem'
  return `Synced ${ago(status.last)}`
}

export function initSyncUI({ sync, sheet, openSheet, toast }) {
  const body = $('.sheet-body', sheet)
  let reveal = null // { phrase, link } while the phrase is on screen
  let working = false
  let joinText = '' // kept so a typo does not wipe what she typed

  const button = (label, cls, onClick) => {
    const btn = make('button', cls, label)
    btn.addEventListener('click', onClick)
    return btn
  }

  async function guarded(fn, errorBox) {
    if (working) return
    working = true
    render()
    try {
      await fn()
    } catch (err) {
      working = false
      render()
      if (errorBox) $(errorBox, body).textContent = err.message
      else toast(err.message)
      return
    }
    working = false
    render()
  }

  async function copy(text, done) {
    try {
      await navigator.clipboard.writeText(text)
      toast(done)
    } catch {
      toast("Couldn't copy. Select the text and copy it by hand.")
    }
  }

  async function qrSvg(link) {
    const { default: qrcode } = await import('./vendor/qrcode.mjs')
    const qr = qrcode(0, 'M')
    qr.addData(link)
    qr.make()
    return qr.createSvgTag({ cellSize: 4, margin: 8, scalable: true, alt: 'QR code that links another device to your synced data' })
  }

  function phraseBlock(phrase) {
    const box = make('div', 'phrase-box')
    const grid = make('ol', 'phrase')
    for (const word of phrase.split(' ')) grid.append(make('li', null, word))
    box.append(grid)
    return box
  }

  async function showPhrase() {
    reveal = { phrase: await sync.phrase(), link: sync.link(), svg: await qrSvg(sync.link()) }
  }

  function renderOff() {
    body.replaceChildren(
      make('p', 'lead', 'Keep your notes, saved passages and place in step across your devices. There is no account. Your data is scrambled on this device with a secret only you hold, so the server only ever stores something unreadable.'),
      button('Turn on sync', 'btn wide', () =>
        guarded(async () => {
          await sync.enable()
          await showPhrase()
          reveal.fresh = true
        }),
      ),
      make('h3', 'sub-head', 'Already using it on another device?'),
      make('p', 'fine', 'Type the 12 words, or open the link or QR code from that device.'),
    )
    const input = make('textarea', 'field')
    input.rows = 3
    input.placeholder = 'twelve words separated by spaces'
    input.setAttribute('aria-label', 'Sync phrase')
    input.autocapitalize = 'none'
    input.spellcheck = false
    input.value = joinText
    input.addEventListener('input', () => (joinText = input.value))
    const error = make('p', 'form-error')
    error.id = 'syncError'
    body.append(
      input,
      error,
      button('Join with phrase', 'btn ghost wide', () =>
        guarded(async () => {
          await sync.join(input.value)
          joinText = ''
          toast('Synced')
        }, '#syncError'),
      ),
    )
  }

  function renderReveal() {
    const children = []
    if (reveal.fresh) {
      children.push(
        make('p', 'lead', 'Sync is on. Write these 12 words down somewhere safe. They are the only way to get your notes back on a new phone, and nobody can reset them for you.'),
      )
    } else {
      children.push(make('p', 'lead', 'To add another device, enter these words there, or scan the code.'))
    }
    const qr = make('div', 'qr')
    qr.innerHTML = reveal.svg // generated by the bundled QR library from our own link
    children.push(
      phraseBlock(reveal.phrase),
      qr,
      make('p', 'fine warn', 'Anyone who has these words can read your notes. Do not post them anywhere.'),
      button('Copy phrase', 'btn ghost wide', () => copy(reveal.phrase, 'Phrase copied')),
      button('Copy link', 'btn ghost wide', () => copy(reveal.link, 'Link copied')),
      button(reveal.fresh ? 'I have saved them' : 'Hide', 'btn wide', () => {
        reveal = null
        render()
      }),
    )
    body.replaceChildren(...children)
  }

  function renderOn() {
    const status = sync.status()
    const line = make('p', 'status-line' + (status.state === 'error' ? ' bad' : ''), status.state === 'error' ? status.error : statusLabel(status))
    body.replaceChildren(
      line,
      button('Sync now', 'btn wide', () => guarded(() => sync.syncNow())),
      button('Add another device', 'btn ghost wide', () =>
        guarded(async () => {
          await showPhrase()
        }),
      ),
      make('h3', 'sub-head', 'Stop syncing'),
      button('Turn off on this device', 'btn ghost wide', () => {
        if (!confirm('Stop syncing on this device? Your notes stay here. Your other devices and the server copy are not touched.')) return
        sync.disconnect()
        render()
      }),
      button('Delete the synced copy', 'danger', () => {
        if (!confirm('Delete the synced copy from the server? Other devices keep their own notes but stop receiving updates.')) return
        guarded(async () => {
          await sync.destroy()
          toast('Synced copy deleted')
        })
      }),
    )
  }

  function render() {
    if (working) {
      body.replaceChildren(make('div', 'spinner center'))
      return
    }
    if (!sync.isOn()) reveal = null
    if (reveal) renderReveal()
    else if (sync.isOn()) renderOn()
    else renderOff()
  }

  sync.onStatus(() => {
    if (sheet.open && !working && !reveal) render()
  })

  return {
    open() {
      reveal = null
      render()
      openSheet(sheet)
    },
  }
}
